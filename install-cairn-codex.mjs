#!/usr/bin/env node
// Install Cairn for Codex: this checkout as a plugin, and the three roles as custom
// agents under $CODEX_HOME/agents. Mirrors vonnegut's install-prose-codex.mjs.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, realpathSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = dirname(fileURLToPath(import.meta.url));
const CODEX_HOME = process.env.CODEX_HOME || join(homedir(), ".codex");
const AGENTS_DIR = join(CODEX_HOME, "agents");
export const MARKER = "# Generated by cairn/install-cairn-codex.mjs.";
const MARKETPLACE = "cairn";
const PLUGIN = "cairn";
export const AGENTS = ["cairn-adversary", "cairn-reviewer", "cairn-witness"];
const HOST_BOUNDARY = `## Codex host boundary

Run as a focused read-only custom agent. Use only the inputs in the task. Do not inspect workspace files, earlier session history, or the ledger. Return the requested output to the parent agent; do not save or apply it yourself.`;

function usage() {
  console.log(`Install Cairn for Codex.

Usage:
  node install-cairn-codex.mjs
  node install-cairn-codex.mjs --check
  node install-cairn-codex.mjs --agents-only
  node install-cairn-codex.mjs --remote

Options:
  --check        Verify the plugin and the three generated custom agents.
  --agents-only  Install or check custom agents without changing plugins.
  --local        Install this checkout (the default); no download.
  --remote       Install GitHub main instead of this checkout.
  --replace-marketplace  Explicitly switch an existing cairn marketplace source.
  --help         Show this help.

Set CODEX_HOME to use a non-default Codex configuration directory.`);
}

function parseArgs(argv) {
  const known = new Set(["--check", "--agents-only", "--local", "--remote", "--replace-marketplace", "--help", "-h"]);
  const unknown = argv.filter((a) => !known.has(a));
  if (unknown.length) throw new Error(`unknown option: ${unknown[0]}`);
  if (argv.includes("--local") && argv.includes("--remote")) throw new Error("Choose --local or --remote, not both");
  return { local: !argv.includes("--remote"), replaceMarketplace: argv.includes("--replace-marketplace"), agentsOnly: argv.includes("--agents-only"), check: argv.includes("--check"), help: argv.includes("--help") || argv.includes("-h") };
}

export function readAgent(name) {
  const source = join(REPO, "agents", `${name}.md`);
  const text = readFileSync(source, "utf8");
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error(`${source}: expected YAML frontmatter`);
  const field = (key) => { const f = match[1].match(new RegExp(`^${key}:\\s*(.+)$`, "m")); if (!f) throw new Error(`${source}: missing ${key}`); return f[1].trim(); };
  if (field("name") !== name) throw new Error(`${source}: name is ${field("name")}, expected ${name}`);
  return { name, description: field("description"), prompt: match[2].trim() };
}

export function renderAgent(name) {
  const agent = readAgent(name);
  const instructions = `${agent.prompt}\n\n${HOST_BOUNDARY}\n`;
  return `${MARKER}\nname = ${JSON.stringify(agent.name)}\ndescription = ${JSON.stringify(agent.description)}\nsandbox_mode = "read-only"\ndeveloper_instructions = ${JSON.stringify(instructions)}\n`;
}

function runCodex(args) {
  const result = spawnSync("codex", args, { encoding: "utf8", timeout: 60000 });
  if (result.error?.code === "ENOENT") throw new Error("codex was not found on PATH");
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`codex ${args.join(" ")} failed: ${(result.stderr || result.stdout || "unknown error").trim()}`);
  return result.stdout;
}

function installPlugin({ local = true, replaceMarketplace = false } = {}, run = runCodex) {
  const sources = JSON.parse(run(["plugin", "marketplace", "list", "--json"]));
  const prior = sources.marketplaces?.find((m) => m.name === MARKETPLACE);
  const desired = local ? REPO : "ConnorBritain/cairn";
  const matches = prior && (local
    ? prior.marketplaceSource?.sourceType === "local" && realpathSync(prior.root) === realpathSync(REPO)
    : prior.marketplaceSource?.sourceType === "git" && prior.marketplaceSource.source === "https://github.com/ConnorBritain/cairn.git");
  if (prior && !matches) {
    if (!replaceMarketplace) throw new Error(`${MARKETPLACE} uses a different source. Use --replace-marketplace to explicitly switch to ${desired}.`);
    run(["plugin", "marketplace", "remove", MARKETPLACE, "--json"]);
  }
  run(["plugin", "marketplace", "add", desired, ...(!local ? ["--ref", "main"] : []), "--json"]);
  run(["plugin", "add", `${PLUGIN}@${MARKETPLACE}`, "--json"]);
  console.log(`  plugin ${PLUGIN}`);
}

export function installAgents(dir = AGENTS_DIR) {
  mkdirSync(dir, { recursive: true });
  for (const name of AGENTS) {
    const target = join(dir, `${name}.toml`);
    const rendered = renderAgent(name);
    if (existsSync(target)) {
      const current = readFileSync(target, "utf8");
      if (!current.startsWith(`${MARKER}\n`)) throw new Error(`${target} already exists and was not generated by this installer`);
    }
    writeFileSync(target, rendered, { encoding: "utf8", mode: 0o600 });
    console.log(`  agent  ${name}`);
  }
}

export function checkAgents(dir = AGENTS_DIR) {
  const problems = [];
  for (const name of AGENTS) {
    const target = join(dir, `${name}.toml`);
    if (!existsSync(target)) { problems.push(`${target}: missing`); continue; }
    if (readFileSync(target, "utf8") !== renderAgent(name)) problems.push(`${target}: differs from this checkout's agent`);
  }
  return problems;
}

function checkPlugin(run = runCodex) {
  const listing = JSON.parse(run(["plugin", "list", "--json"]));
  const installed = listing.installed?.find((p) => p.name === PLUGIN && p.marketplaceName === MARKETPLACE);
  return installed ? [] : [`plugin ${PLUGIN}@${MARKETPLACE} is not installed`];
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const opts = parseArgs(process.argv.slice(2));
    if (opts.help) { usage(); process.exit(0); }
    if (opts.check) {
      const problems = [...(opts.agentsOnly ? [] : checkPlugin()), ...checkAgents()];
      if (problems.length) { for (const p of problems) console.error(p); process.exit(1); }
      console.log(`cairn for Codex: ${opts.agentsOnly ? "" : "plugin and "}${AGENTS.length} custom agents verified`);
      process.exit(0);
    }
    if (!opts.agentsOnly) installPlugin(opts);
    installAgents();
    console.log("Start a new Codex session, then ask for /cairn, /cairn-review or /cairn-score.");
  } catch (e) {
    console.error(`install-cairn-codex: ${e.message}`);
    process.exit(1);
  }
}
